import type { Request, Router } from "express";
import type { PluginContext } from "@termix-ssh/plugin-sdk/backend";
import { identifier, NomadError } from "./client.js";
import { id, listQuery, objectBody, route } from "./route-utils.js";

type ObjectValue = Record<string, unknown>;
type Kind = "namespaces" | "policies" | "roles" | "tokens" | "auth-methods" | "binding-rules" | "sentinel";
const root = "/hosts/:hostId/administration";
const paths: Record<Kind, { list: string; item: string; create: string; key: string }> = {
  namespaces: { list: "/v1/namespaces", item: "/v1/namespace", create: "/v1/namespace", key: "Name" },
  policies: { list: "/v1/acl/policies", item: "/v1/acl/policy", create: "/v1/acl/policy", key: "Name" },
  roles: { list: "/v1/acl/roles", item: "/v1/acl/role", create: "/v1/acl/role", key: "ID" },
  tokens: { list: "/v1/acl/tokens", item: "/v1/acl/token", create: "/v1/acl/token", key: "AccessorID" },
  "auth-methods": { list: "/v1/acl/auth-methods", item: "/v1/acl/auth-method", create: "/v1/acl/auth-method", key: "Name" },
  "binding-rules": { list: "/v1/acl/binding-rules", item: "/v1/acl/binding-rule", create: "/v1/acl/binding-rule", key: "ID" },
  sentinel: { list: "/v1/sentinel/policies", item: "/v1/sentinel/policy", create: "/v1/sentinel/policy", key: "Name" },
};

function object(value: unknown, status = 400): ObjectValue {
  if (!value || typeof value !== "object" || Array.isArray(value)) throw new NomadError(status, "A JSON object is required");
  return value as ObjectValue;
}
function text(value: unknown, label: string, required = false): string {
  if (typeof value !== "string" || value.length > 1024 * 1024 || (required && !value.trim())) throw new NomadError(400, `Invalid ${label}`);
  return value;
}
function choice(value: unknown, label: string, choices: string[]): string {
  if (typeof value !== "string" || !choices.includes(value)) throw new NomadError(400, `Invalid ${label}`);
  return value;
}
function strings(value: unknown, label: string): string[] {
  if (!Array.isArray(value) || value.length > 1000) throw new NomadError(400, `Invalid ${label}`);
  return value.map(item => identifier(item, label));
}
function name(value: unknown): string {
  const result = identifier(value, "name");
  if (!/^[a-zA-Z0-9_.-]+$/.test(result)) throw new NomadError(400, "Names may contain only letters, numbers, dots, underscores and hyphens");
  return result;
}
function resourceId(req: Request, kind: Kind): string {
  const encoded = id(req, "resourceId");
  if (["tokens", "roles", "binding-rules"].includes(kind) && !/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(req.params.resourceId as string)) {
    throw new NomadError(400, "A Nomad-generated UUID is required");
  }
  return encoded;
}
function matching(value: unknown, kind: Kind, expected: string): ObjectValue {
  const result = object(value, 502);
  if (result[paths[kind].key] !== expected) throw new NomadError(409, "Nomad resource identity mismatch");
  return result;
}
function input(kind: Kind, body: ObjectValue, expected?: string): ObjectValue {
  const result: ObjectValue = {};
  const key = paths[kind].key;
  if (expected !== undefined) {
    if (body[key] !== undefined && body[key] !== expected) throw new NomadError(400, "Resource identity cannot change");
    result[key] = expected;
  } else if (key !== "Name" && body[key] !== undefined && body[key] !== "") {
    throw new NomadError(400, `${key} is generated by Nomad`);
  }
  if (kind !== "tokens" && kind !== "binding-rules") result.Name = name(body.Name);
  for (const field of ["Description"]) if (body[field] !== undefined && kind !== "tokens" && kind !== "auth-methods") result[field] = text(body[field], field);
  switch (kind) {
    case "namespaces":
      if (body.Quota !== undefined) result.Quota = text(body.Quota, "quota");
      for (const field of ["Capabilities", "NodePoolConfiguration", "VaultConfiguration", "ConsulConfiguration", "Meta", "RequiredExtraClaims", "OptionalExtraClaims"]) {
        if (body[field] !== undefined) result[field] = body[field] === null ? null : object(body[field]);
      }
      break;
    case "policies":
      result.Rules = text(body.Rules, "HCL rules", true);
      if (body.JobACL !== undefined) {
        const job = object(body.JobACL);
        result.JobACL = { Namespace: identifier(job.Namespace, "job namespace"), JobID: identifier(job.JobID, "job ID"), ...(job.Group ? { Group: identifier(job.Group, "group") } : {}), ...(job.Task ? { Task: identifier(job.Task, "task") } : {}) };
      }
      break;
    case "roles":
      if (!Array.isArray(body.Policies) || !body.Policies.length) throw new NomadError(400, "At least one policy link is required");
      result.Policies = body.Policies.map(link => ({ Name: name(object(link).Name) }));
      break;
    case "tokens":
      if (Object.hasOwn(body, "SecretID")) throw new NomadError(400, "Token secrets cannot be supplied or replaced");
      result.Name = text(body.Name ?? "", "token name");
      result.Type = choice(body.Type, "token type", ["client", "management"]);
      result.Policies = strings(body.Policies ?? [], "policy name");
      if (!Array.isArray(body.Roles ?? [])) throw new NomadError(400, "Invalid token role links");
      result.Roles = ((body.Roles ?? []) as unknown[]).map(link => {
        const role = object(link);
        return role.ID ? { ID: identifier(role.ID, "role ID") } : { Name: name(role.Name) };
      });
      if (typeof body.Global !== "boolean") throw new NomadError(400, "Global must be a boolean");
      result.Global = body.Global;
      if (body.ExpirationTime !== undefined && body.ExpirationTime !== null && body.ExpirationTime !== "") {
        const expiration = text(body.ExpirationTime, "expiration time", true);
        if (!Number.isFinite(Date.parse(expiration))) throw new NomadError(400, "Invalid expiration time");
        result.ExpirationTime = expiration;
      }
      if (body.ExpirationTTL !== undefined && body.ExpirationTTL !== "") {
        if (expected !== undefined) throw new NomadError(400, "Expiration TTL may only be set when creating a token");
        result.ExpirationTTL = text(body.ExpirationTTL, "expiration TTL", true);
      }
      break;
    case "auth-methods":
      result.Type = choice(body.Type, "authentication type", ["OIDC", "JWT"]);
      result.TokenLocality = choice(body.TokenLocality, "token locality", ["local", "global"]);
      result.MaxTokenTTL = text(body.MaxTokenTTL, "maximum token TTL", true);
      if (typeof body.Default !== "boolean") throw new NomadError(400, "Default must be a boolean");
      result.Default = body.Default;
      result.TokenNameFormat = text(body.TokenNameFormat ?? "", "token name format");
      result.Config = object(body.Config);
      break;
    case "binding-rules":
      result.AuthMethod = name(body.AuthMethod);
      result.Selector = text(body.Selector ?? "", "selector");
      result.BindType = choice(body.BindType, "binding type", ["role", "policy", "management"]);
      result.BindName = text(body.BindName ?? "", "binding name", body.BindType !== "management");
      break;
    case "sentinel":
      result.Scope = choice(body.Scope, "policy scope", ["submit-job", "submit-host-volume", "submit-csi-volume"]);
      result.EnforcementLevel = choice(body.EnforcementLevel, "enforcement level", ["advisory", "soft-mandatory", "hard-mandatory"]);
      result.Policy = text(body.Policy, "Sentinel policy", true);
      break;
  }
  return result;
}
function withoutTokenSecret(value: unknown): ObjectValue {
  const { SecretID: _secret, ...safe } = object(value, 502);
  return safe;
}

export function registerAdministrationRoutes(router: Router, ctx: PluginContext): void {
  router.use(root, (_req, res, next) => { res.setHeader("Cache-Control", "no-store"); next(); });
  async function connectionToken(req: Request): Promise<string> {
    const value = await ctx.settings.getHost<unknown>(Number(req.params.hostId), "token");
    return typeof value === "string" ? value : "";
  }
  async function safe(req: Request, value: unknown): Promise<unknown> {
    const token = await connectionToken(req);
    // Administration can return user-authored HCL/config as well as ACL records.
    // Redact the connection credential even if upstream embeds it outside SecretID.
    function redact(item: unknown): unknown {
      if (typeof item === "string") return token ? item.replaceAll(token, "[connection credential redacted]") : item;
      if (Array.isArray(item)) return item.map(redact);
      if (item && typeof item === "object") return Object.fromEntries(Object.entries(item).map(([key, entry]) => [token ? key.replaceAll(token, "[connection credential redacted]") : key, redact(entry)]));
      return item;
    }
    return redact(value);
  }
  async function createdToken(req: Request, value: unknown): Promise<unknown> {
    const token = object(value, 502);
    const secret = typeof token.SecretID === "string" ? token.SecretID : "";
    const configured = await connectionToken(req);
    return safe(req, { token: withoutTokenSecret(token), ...(secret && secret !== configured ? { secret } : { secretUnavailable: "No new secret is available. The configured connection credential is never revealed." }) });
  }
  for (const kind of Object.keys(paths) as Kind[]) {
    const spec = paths[kind];
    const endpoint = `${root}/${kind}`;
    router.get(endpoint, route(ctx, async (req, client, ns) => {
      const page = await client.page(spec.list, ns, listQuery(req));
      return safe(req, { ...page, items: kind === "tokens" ? page.items.map(withoutTokenSecret) : page.items });
    }, "administer"));
    router.get(`${endpoint}/:resourceId`, route(ctx, async (req, client, ns) => {
      const encoded = resourceId(req, kind);
      const value = matching(await client.request(`${spec.item}/${encoded}`, ns), kind, decodeURIComponent(encoded));
      return safe(req, kind === "tokens" ? withoutTokenSecret(value) : value);
    }, "administer"));
    router.post(endpoint, route(ctx, async (req, client, ns) => {
      const body = input(kind, objectBody(req));
      const path = ["policies", "sentinel"].includes(kind) ? `${spec.create}/${encodeURIComponent(String(body.Name))}` : spec.create;
      const value = await client.request(path, ns, { method: "PUT", body });
      return kind === "tokens" ? createdToken(req, value) : safe(req, value);
    }, "administer"));
    router.put(`${endpoint}/:resourceId`, route(ctx, async (req, client, ns) => {
      const encoded = resourceId(req, kind);
      const body = input(kind, objectBody(req), decodeURIComponent(encoded));
      const path = kind === "namespaces" ? spec.create : `${spec.item}/${encoded}`;
      const value = await client.request(path, ns, { method: "PUT", body });
      return safe(req, kind === "tokens" ? withoutTokenSecret(value) : value);
    }, "administer"));
    router.delete(`${endpoint}/:resourceId`, route(ctx, async (req, client, ns) => {
      const encoded = resourceId(req, kind);
      return safe(req, await client.request(`${spec.item}/${encoded}`, ns, { method: "DELETE" }));
    }, "administer"));
  }
  router.post(`${root}/tokens/:resourceId/secret`, route(ctx, async (req, client, ns, res) => {
    res.setHeader("Cache-Control", "no-store");
    const encoded = resourceId(req, "tokens");
    const token = matching(await client.request(`/v1/acl/token/${encoded}`, ns), "tokens", decodeURIComponent(encoded));
    const secret = token.SecretID;
    if (typeof secret !== "string" || !secret) throw new NomadError(404, "No token secret is available");
    if (secret === await connectionToken(req)) throw new NomadError(403, "The configured connection credential cannot be revealed");
    return safe(req, { secret });
  }, "administer"));
  router.post(`${root}/tokens/:resourceId/clone`, route(ctx, async (req, client, ns) => {
    const encoded = resourceId(req, "tokens");
    const source = matching(await client.request(`/v1/acl/token/${encoded}`, ns), "tokens", decodeURIComponent(encoded));
    const requested = objectBody(req);
    const body = input("tokens", {
      Name: text(requested.Name, "clone name", true), Type: source.Type, Policies: source.Policies ?? [], Roles: source.Roles ?? [], Global: source.Global,
      ...(requested.ExpirationTTL ? { ExpirationTTL: requested.ExpirationTTL } : {}),
      ...(requested.ExpirationTime ? { ExpirationTime: requested.ExpirationTime } : {}),
    });
    return createdToken(req, await client.request("/v1/acl/token", ns, { method: "PUT", body }));
  }, "administer"));
}
